// ─────────────────────────────────────────────────────────────────────────────
// バッチ分割ユーティリティ
// ─────────────────────────────────────────────────────────────────────────────
function chunk<T>(arr: T[], size: number): T[][] {
  const result: T[][] = [];
  for (let i = 0; i < arr.length; i += size) result.push(arr.slice(i, i + size));
  return result;
}

// ─────────────────────────────────────────────────────────────────────────────
// メイン
// ─────────────────────────────────────────────────────────────────────────────
async function seed() {
  console.log(`🌱 食品データ投入開始 (${FOODS.length} 件)...`);

  // ── Phase 1: 食品マスタ (createMany + skipDuplicates, 500件バッチ) ────────
  console.log("  [1/3] 食品マスタ...");
  const foodRows = FOODS.map((f) => ({
    foodCode:     f.code,
    nameJa:       f.name,
    nameKana:     f.kana,
    category:     f.cat,
    caloriesKcal: f.kcal,
    proteinG:     f.p,
    fatG:         f.f,
    carbG:        f.c,
    source:       "mext" as const,
  }));
  for (const batch of chunk(foodRows, 500)) {
    await prisma.genericFood.createMany({ data: batch, skipDuplicates: true });
  }

  // ── Phase 2: ID マップ取得 ────────────────────────────────────────────────
  const existing = await prisma.genericFood.findMany({
    where: { foodCode: { in: FOODS.map((f) => f.code) } },
    select: { id: true, foodCode: true },
  });
  const byCode = new Map(existing.map((f) => [f.foodCode!, f.id]));
  const foodIds = [...byCode.values()];

  // ── Phase 3: サービングサイズ (削除→再作成, 500件バッチ) ────────────────
  console.log("  [2/3] サービングサイズ...");
  await prisma.foodServing.deleteMany({ where: { genericFoodId: { in: foodIds } } });

  const servingRows: {
    genericFoodId: string; servingName: string; servingG: number; sortOrder: number;
  }[] = [];
  for (const f of FOODS) {
    const id = byCode.get(f.code);
    if (!id) continue;
    servingRows.push({ genericFoodId: id, servingName: "100g", servingG: 100, sortOrder: 0 });
    for (const [name, g, order] of SERVINGS[f.code] ?? []) {
      servingRows.push({ genericFoodId: id, servingName: name, servingG: g, sortOrder: order });
    }
  }
  for (const batch of chunk(servingRows, 500)) {
    await prisma.foodServing.createMany({ data: batch });
  }

  // ── Phase 4: エイリアス (削除→再作成, 500件バッチ) ──────────────────────
  console.log("  [3/3] エイリアス...");
  await prisma.foodAlias.deleteMany({ where: { genericFoodId: { in: foodIds } } });

  const aliasRows: { alias: string; genericFoodId: string }[] = [];
  for (const [code, aliases] of Object.entries(ALIASES)) {
    const id = byCode.get(code);
    if (!id) continue;
    for (const alias of aliases) aliasRows.push({ alias, genericFoodId: id });
  }
  for (const batch of chunk(aliasRows, 500)) {
    await prisma.foodAlias.createMany({ data: batch });
  }

  const count = await prisma.genericFood.count();
  console.log(`✅ 完了: GenericFood ${count} 件, Serving ${servingRows.length} 件, Alias ${aliasRows.length} 件`);
  await prisma.$disconnect();
}

seed().catch((e) => {
  console.error(e);
  prisma.$disconnect();
  process.exit(1);
});
